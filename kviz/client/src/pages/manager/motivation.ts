const LS_KEY = 'motivation_last';

export function getMotivation(planPct: number | null, overdueCount: number): string {
  if (planPct != null && planPct >= 100) {
    return PLAN_DONE_PHRASES[Math.floor(Math.random() * PLAN_DONE_PHRASES.length)];
  }
  if (planPct != null && planPct >= 90) {
    return CLOSE_PHRASES[Math.floor(Math.random() * CLOSE_PHRASES.length)];
  }
  if (overdueCount > 0) {
    return OVERDUE_PHRASES[Math.floor(Math.random() * OVERDUE_PHRASES.length)];
  }

  let last = '';
  try { last = localStorage.getItem(LS_KEY) ?? ''; } catch {}
  const pool = PHRASES.filter(p => p !== last);
  const phrase = pool[Math.floor(Math.random() * pool.length)] ?? PHRASES[0];
  try { localStorage.setItem(LS_KEY, phrase); } catch {}
  return phrase;
}
